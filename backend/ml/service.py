    def backtest(self, req: dict[str, Any]) -> dict[str, Any]:
        series = self._demo_market(180)
        values = np.array([r["close"] for r in series], dtype=float)
        rets = np.diff(values) / values[:-1]
        signal = np.where(np.sin(np.arange(len(rets)) / 11) > -0.15, 1.0, 0.0)
        strategy = rets * signal
        equity = req.get("initial_capital", 10000) * np.cumprod(1 + strategy)
        peak = np.maximum.accumulate(equity)
        drawdown = equity / peak - 1
        total_return = float(equity[-1] / equity[0] - 1)
        max_dd = float(drawdown.min())
        wins = int((strategy > 0).sum())
        losses = int((strategy < 0).sum())
        return {
            "mode": "demo",
            "model": req.get("model", "hybrid"),
            "instrument": req.get("instrument", "GC=F"),
            "timeframe": req.get("timeframe", "1d"),
            "total_return": round(total_return, 4),
            "maximum_drawdown": round(abs(max_dd), 4),
            "number_of_trades": int((signal[1:] != signal[:-1]).sum() + 1),
            "win_rate": round(wins / max(1, wins + losses), 4),
            "profit_factor": round(float(strategy[strategy > 0].sum() / max(1e-9, abs(strategy[strategy < 0].sum()))), 3),
            "sharpe_ratio": round(float(strategy.mean() / (strategy.std() + 1e-9) * math.sqrt(252)), 3),
            "equity_curve": [{"timestamp": series[i + 1]["timestamp"], "equity": round(float(equity[i]), 2)} for i in range(len(equity))],
            "drawdown_curve": [{"timestamp": series[i + 1]["timestamp"], "drawdown": round(float(drawdown[i]), 4)} for i in range(len(drawdown))],
            "warning": "Demo backtest. Replace with artifact-backed historical model signals before using as research evidence.",
        }


