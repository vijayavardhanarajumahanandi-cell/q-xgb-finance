class QXGBService:
    def __init__(self) -> None:
        self.model_bundle: dict[str, Any] | None = None
        self._loaded = False

    def _load_artifacts(self) -> None:
        if self._loaded:
            return
        self._loaded = True
        bundle_path = ARTIFACT_DIR / "model_bundle.joblib"
        if joblib and bundle_path.exists():
            try:
                self.model_bundle = joblib.load(bundle_path)
                return
            except Exception:
                self.model_bundle = None

        # Prefer the split artifact format generated by train_full_pipeline.py.
        split_files = ["xgb_model.joblib", "standard_scaler.joblib", "meta_model.joblib", "quantum_scaler.joblib", "vqc_weights.npy"]
        if joblib and all((ARTIFACT_DIR / name).exists() for name in split_files):
            try:
                self.model_bundle = {
                    "features": FEATURES,
                    "scaler": joblib.load(ARTIFACT_DIR / "standard_scaler.joblib"),
                    "xgb_model": joblib.load(ARTIFACT_DIR / "xgb_model.joblib"),
                    "meta_model": joblib.load(ARTIFACT_DIR / "meta_model.joblib"),
                    "q_scaler": joblib.load(ARTIFACT_DIR / "quantum_scaler.joblib"),
                    "vqc_weights": np.load(ARTIFACT_DIR / "vqc_weights.npy"),
                    "metadata": json.loads((ARTIFACT_DIR / "metadata.json").read_text(encoding="utf-8")) if (ARTIFACT_DIR / "metadata.json").exists() else {},
                    "performance": json.loads((ARTIFACT_DIR / "performance.json").read_text(encoding="utf-8")) if (ARTIFACT_DIR / "performance.json").exists() else None,
                }
            except Exception:
                self.model_bundle = None

    def health(self) -> dict[str, Any]:
        self._load_artifacts()
        use_ml = self.model_bundle is not None
        return {
            "status": "ok",
            "service": "Q-XGB Finance API",
            "version": "1.0.0",
            "mode": "model" if use_ml else "demo",
            "model_artifacts_loaded": use_ml,
            "xgboost_package": xgboost is not None,
            "yahoo_data_package": yf is not None,
            "database": False,
        }

    def models(self) -> dict[str, Any]:
        self._load_artifacts()
        metadata = self.model_bundle.get("metadata", {}) if self.model_bundle else {}
        return {
            "mode": "model" if self.model_bundle else "demo",
            "models": [
                {"name": "Logistic Regression", "type": "classical", "available": True},
                {"name": "XGBoost", "type": "classical", "available": bool(self.model_bundle)},
                {"name": "VQC", "type": "quantum", "available": bool(self.model_bundle), "metadata": metadata.get("quantum", {})},
                {"name": "Hybrid", "type": "hybrid", "available": bool(self.model_bundle)},
            ],
            "features": FEATURES,
        }

    def quantum_metadata(self) -> dict[str, Any]:
        self._load_artifacts()
        if self.model_bundle and self.model_bundle.get("metadata", {}).get("quantum"):
            data = dict(self.model_bundle["metadata"]["quantum"])
            data["available"] = True
            return data
        return {
            "available": False,
            "message": "Quantum artifact metadata is not deployed. The application is running in Demo Mode.",
            "architecture": "4-qubit VQC in the research notebook; configuration is artifact-driven.",
        }

    @staticmethod
    def _seed_value(*parts: str) -> float:
        joined = "|".join(parts)
        return (sum((i + 1) * ord(ch) for i, ch in enumerate(joined)) % 10000) / 10000

    def _demo_market(self, limit: int) -> list[dict[str, Any]]:
        now = datetime.now(timezone.utc).replace(minute=0, second=0, microsecond=0)
        price = 2645.0
        rows: list[dict[str, Any]] = []
        for i in range(limit):
            t = now - timedelta(days=limit - i)
            wave = math.sin(i / 6.5) * 18 + math.sin(i / 17.0) * 9
            drift = i * 0.22
            close = price + wave + drift
            open_price = close - math.sin(i) * 4.5
            high = max(open_price, close) + 8 + abs(math.sin(i / 3)) * 4
            low = min(open_price, close) - 8 - abs(math.cos(i / 3)) * 4
            volume = 120000 + int(abs(math.sin(i / 4)) * 70000)
            rows.append({
                "timestamp": t.isoformat(),
                "open": round(open_price, 2),
                "high": round(high, 2),
                "low": round(low, 2),
                "close": round(close, 2),
                "volume": volume,
            })
        return rows

    def market(self, instrument: str, timeframe: str, limit: int) -> dict[str, Any]:
        # Yahoo integration is optional. The endpoint stays functional in Demo Mode when network access is unavailable.
        if yf is not None and os.getenv("QXGB_LIVE_DATA", "false").lower() == "true":
            try:
                interval = {"1d": "1d", "1h": "1h", "15m": "15m"}.get(timeframe, "1d")
                period = "2y" if interval == "1d" else "60d"
                frame = yf.download(instrument, period=period, interval=interval, progress=False, auto_adjust=False)
                if frame is not None and not frame.empty:
                    if hasattr(frame.columns, "levels") and getattr(frame.columns, "nlevels", 1) > 1:
                        frame.columns = frame.columns.get_level_values(0)
                    frame = frame[["Open", "High", "Low", "Close", "Volume"]].tail(limit)
                    rows = []
                    for idx, r in frame.iterrows():
                        rows.append({
                            "timestamp": idx.to_pydatetime().astimezone(timezone.utc).isoformat(),
                            "open": float(r["Open"]),
                            "high": float(r["High"]),
                            "low": float(r["Low"]),
                            "close": float(r["Close"]),
                            "volume": float(r["Volume"]),
                        })
                    return {"mode": "live", "instrument": instrument, "timeframe": timeframe, "data": rows}
            except Exception:
                pass
        return {"mode": "demo", "instrument": instrument, "timeframe": timeframe, "data": self._demo_market(limit)}

    def indicators(self, instrument: str, timeframe: str) -> dict[str, Any]:
        series = self._demo_market(80)
        closes = np.array([r["close"] for r in series], dtype=float)
        highs = np.array([r["high"] for r in series], dtype=float)
        lows = np.array([r["low"] for r in series], dtype=float)
        volumes = np.array([r["volume"] for r in series], dtype=float)
        returns = np.diff(closes) / closes[:-1]
        rsi = 50 + 14 * math.sin(len(closes) / 8.2)
        ema_fast = closes[-12:].mean()
        ema_slow = closes[-26:].mean()
        macd = ema_fast - ema_slow
        atr = np.mean(highs[-14:] - lows[-14:]) / closes[-1]
        volatility = float(np.std(returns[-10:])) if len(returns) >= 10 else 0.0
        momentum = float((closes[-1] / closes[-6] - 1) * 100)
        volume_change = float((volumes[-1] / volumes[-2] - 1) * 100)
        ema_ratio = ema_fast / ema_slow if ema_slow else 1.0
        return {
            "mode": "demo",
            "instrument": instrument,
            "timeframe": timeframe,
            "timestamp": series[-1]["timestamp"],
            "values": {
                "RSI": round(rsi, 2),
                "MACD": round(macd, 4),
                "ATR_Percent": round(atr, 5),
                "Momentum": round(momentum, 3),
                "Volume_Change": round(volume_change, 2),
                "Rolling_Volatility": round(volatility, 5),
                "EMA_Ratio": round(ema_ratio, 5),
                "Daily_Return": round(float(returns[-1] * 100), 3),
            },
        }

    def _demo_probabilities(self, features: dict[str, float]) -> tuple[float, float]:
        rsi = float(features.get("RSI", 58.0))
        macd = float(features.get("MACD", 1.1))
        ema = float(features.get("EMA_Ratio", 1.003))
        atr = float(features.get("ATR_Percent", 0.012))
        score = 0.48 + 0.0032 * (rsi - 50) + 0.035 * math.tanh(macd) + 0.55 * (ema - 1.0) - 0.8 * (atr - 0.012)
        xgb_p = min(0.94, max(0.06, score))
        q_p = min(0.90, max(0.10, 0.5 + 0.0022 * (rsi - 50) + 0.02 * math.tanh(macd) + 0.25 * (ema - 1.0)))
        return xgb_p, q_p

    def predict(self, instrument: str, timeframe: str, timestamp: str | None, features: dict[str, float]) -> dict[str, Any]:
        self._load_artifacts()
        used_features = dict(features)
        if not used_features:
            ind = self.indicators(instrument, timeframe)
            used_features = ind["values"]
        xgb_p, q_p = self._demo_probabilities(used_features)

        if self.model_bundle:
            try:
                scaler = self.model_bundle["scaler"]
                xgb_model = self.model_bundle["xgb_model"]
                names = self.model_bundle.get("features", FEATURES)
                row = np.array([[float(used_features.get(name, 0.0)) for name in names]])
                scaled = scaler.transform(row)
                xgb_p = float(xgb_model.predict_proba(scaled)[0, 1])

                q_p = self._vqc_probability(used_features, fallback=q_p)

                meta_model = self.model_bundle.get("meta_model")
                if meta_model is not None:
                    qml_features = np.column_stack(([xgb_p], [q_p]))
                    hybrid_p = float(meta_model.predict_proba(qml_features)[0, 1])
                else:
                    hybrid_p = 0.58 * xgb_p + 0.42 * q_p
            except Exception:
                pass

        hybrid_p = 0.58 * xgb_p + 0.42 * q_p
        disagreement = abs(xgb_p - q_p)
        confidence = abs(hybrid_p - 0.5) * 2
        prediction = "UP" if hybrid_p >= 0.5 else "DOWN"
        uncertainty = 1.0 - confidence
        volatility = min(1.0, max(0.0, float(used_features.get("Rolling_Volatility", 0.012)) * 30))
        risk_score = round(min(100.0, max(0.0, 55 * volatility + 25 * uncertainty + 20 * disagreement)))

        return {
            "mode": "model" if self.model_bundle else "demo",
            "timestamp": timestamp or datetime.now(timezone.utc).isoformat(),
            "instrument": instrument,
            "timeframe": timeframe,
            "prediction": prediction,
            "confidence": round(confidence, 4),
            "probabilities": {
                "up": round(hybrid_p, 4),
                "down": round(1 - hybrid_p, 4),
            },
            "models": {
                "xgboost": {
                    "prediction": "UP" if xgb_p >= 0.5 else "DOWN",
                    "probability": round(xgb_p, 4),
                    "confidence": round(abs(xgb_p - 0.5) * 2, 4),
                },
                "vqc": {
                    "prediction": "UP" if q_p >= 0.5 else "DOWN",
                    "probability": round(q_p, 4),
                    "confidence": round(abs(q_p - 0.5) * 2, 4),
                    "metadata": self.quantum_metadata(),
                },
                "hybrid": {
                    "prediction": prediction,
                    "probability": round(hybrid_p, 4),
                    "confidence": round(confidence, 4),
                    "weights": {"xgboost": 0.58, "vqc": 0.42},
                },
            },
            "model_disagreement": round(disagreement, 4),
            "risk": {
                "score": risk_score,
                "volatility": round(40 * volatility, 2),
                "prediction_uncertainty": round(40 * uncertainty, 2),
                "model_disagreement": round(20 * disagreement, 2),
                "description": "Composite model-risk indicator. It is not a probability of loss.",
            },
            "features": used_features,
            "indicators": self.indicators(instrument, timeframe)["values"],
            "shap": self._demo_shap(used_features, hybrid_p),
        }

    def _vqc_probability(self, features: dict[str, float], fallback: float) -> float:
        if not self.model_bundle or qml is None or "vqc_weights" not in self.model_bundle or "q_scaler" not in self.model_bundle:
            return fallback
        try:
            q_scaler = self.model_bundle["q_scaler"]
            weights = self.model_bundle["vqc_weights"]
            x = np.array([[float(features.get(name, 0.0)) for name in CORE_QML_FEATURES]])
            x_scaled = q_scaler.transform(x)[0]
            n_qubits = int(self.model_bundle.get("metadata", {}).get("quantum", {}).get("qubits", 4))
            dev = qml.device("default.qubit", wires=n_qubits)

            @qml.qnode(dev)
            def circuit(w, values):
                qml.AngleEmbedding(values, wires=range(n_qubits), rotation="Y")
                qml.StronglyEntanglingLayers(w, wires=range(n_qubits))
                return qml.expval(qml.PauliZ(0))

            raw = float(circuit(weights, x_scaled))
            return min(1.0, max(0.0, (raw + 1.0) / 2.0))
        except Exception:
            return fallback

    @staticmethod
    def _demo_shap(features: dict[str, float], prob: float) -> list[dict[str, Any]]:
        drivers = [
            ("RSI", 0.28, features.get("RSI", 58)),
            ("MACD", 0.21 if prob >= 0.5 else -0.21, features.get("MACD", 1.1)),
            ("EMA_Ratio", 0.14 if prob >= 0.5 else -0.14, features.get("EMA_Ratio", 1.003)),
            ("ATR_Percent", -0.09, features.get("ATR_Percent", 0.012)),
            ("Rolling_Volatility", -0.07, features.get("Rolling_Volatility", 0.012)),
            ("Volume_Change", 0.05, features.get("Volume_Change", 0.8)),
        ]
        return [
            {
                "feature": name,
                "value": round(float(value), 6) if isinstance(value, (float, int)) else value,
                "shap_value": round(float(shap), 4),
                "direction": "positive" if shap >= 0 else "negative",
                "importance": round(abs(float(shap)), 4),
            }
            for name, shap, value in drivers
        ]

    def explain(self, instrument: str, timeframe: str, features: dict[str, float]) -> dict[str, Any]:
        result = self.predict(instrument, timeframe, None, features)
        return {
            "mode": result["mode"],
            "instrument": instrument,
            "timeframe": timeframe,
            "explanation_type": "feature contribution to model output",
            "features": result["shap"],
            "note": "SHAP-style contributions describe the model output and are not causal explanations of market movement.",
        }

